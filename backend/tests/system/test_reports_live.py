"""Phase 11 on the running stack: a claim with real synthetic documents is processed by the real agents,
approved by a reviewer, and its reports are generated by the ``reports`` worker. Every evidence label of
the JSON version is printed in the PDF, and page evidence points at this claim's real documents.
An escalation email is delivered by the beat-driven dispatcher to the Mailpit SMTP server."""

from __future__ import annotations

import time
from typing import Any

import httpx
import pypdfium2
import pytest

from tests.system.conftest import SystemClient
from tests.system.test_agents_live import book  # noqa: F401 - shared fixture
from tests.system.test_reviews_live import _key, _reviewer, _to_review

pytestmark = pytest.mark.system
MAILPIT = "http://127.0.0.1:8025"


def _ready(admin: SystemClient, claim_id: str, fmt: str) -> dict[str, Any]:
    created = admin.post(f"/claims/{claim_id}/reports", json={"format": fmt}, headers=_key())
    assert created.status_code == 202, created.text
    deadline = time.monotonic() + 120
    while time.monotonic() < deadline:
        rows = admin.get(f"/claims/{claim_id}/reports").json()
        row: dict[str, Any] = next(r for r in rows if r["id"] == created.json()["id"])
        if row["status"] != "queued":
            assert row["status"] == "ready", row
            return row
        time.sleep(1)
    pytest.fail("report was not generated")


def _mail_to(address: str) -> dict[str, Any]:
    deadline = time.monotonic() + 60  # beat dispatches pending email every 10 s
    while time.monotonic() < deadline:
        found: dict[str, Any] = httpx.get(
            f"{MAILPIT}/api/v1/search", params={"query": f"to:{address}"}, timeout=10
        ).json()
        if found["messages_count"]:
            message: dict[str, Any] = httpx.get(
                f"{MAILPIT}/api/v1/message/{found['messages'][0]['ID']}", timeout=10
            ).json()
            return message
        time.sleep(2)
    pytest.fail(f"no email delivered to {address}")


def test_report_from_real_agents_cites_document_evidence(
    admin: SystemClient,
    base_url: str,
    book: dict[str, Any],  # noqa: F811
) -> None:
    story = "Rear-ended at a junction in Leeds while waiting at a red light."
    claim_id, _, ws = _to_review(admin, book, story)
    review = ws["review"]
    url = f"/claims/{claim_id}/reviews/{review['id']}"
    first, _ = _reviewer(admin, base_url, "5000.00", fraud_override=True)
    second, sid = _reviewer(admin, base_url, "5000.00", fraud_override=True)
    escalated = first.post(f"{url}/escalate", json={"to_user_id": sid, "reason": "please check the estimate"})
    assert escalated.status_code == 200, escalated.text
    body = {"approved_amount": review["payout"], "reason": "verified", "override_reason": "reviewed"}
    decided = second.post(f"{url}/approve", json=body, headers=_key())
    assert decided.status_code == 200, decided.text
    if decided.json()["status"] == "awaiting_second_approval":
        assert first.post(f"{url}/second-approval", json={}, headers=_key()).status_code == 200

    js = _ready(admin, claim_id, "json")
    pdf = _ready(admin, claim_id, "pdf")
    report = admin.get(f"/reports/{js['id']}/download").json()
    evidence = {e["ref"]: e for e in report["evidence"]}
    pages = [e for e in report["evidence"] if e["kind"] == "page"]
    doc_ids = {d["id"] for d in report["documents"]}
    assert pages and all(e["id"] in doc_ids for e in pages)  # evidence points at this claim's documents
    assert report["assessment"]["status"] == "calculated" and report["assessment"]["line_items"]
    assert all(set(li["evidence"]) <= set(evidence) for li in report["assessment"]["line_items"])
    assert report["decisions"][-1]["decision"] == "approved" and report["decisions"][-1]["mode"] == "human"

    data = admin.get(f"/reports/{pdf['id']}/download").content
    assert data[:5] == b"%PDF-"
    doc = pypdfium2.PdfDocument(data)
    text = "\n".join(doc[i].get_textpage().get_text_range() for i in range(len(doc)))
    missing = [ref for ref in evidence if ref not in text]
    assert not missing, missing
    assert report["claim"]["reference"] in text and "Evidence index" in text

    me = second.get("/auth/me").json()["user"]
    assert "escalated to you" in _mail_to(me["email"])["Subject"]
