import { expect, test } from "@playwright/test";

import { createMotorClaim, registerOrganisation } from "./helpers";

test("reports are generated by the worker and downloaded; notifications and integrations work", async ({ page }) => {
  test.setTimeout(180_000);
  await registerOrganisation(page);
  const claimId = await createMotorClaim(page);

  await page.goto(`/claims/${claimId}?tab=reports`);
  const panel = page.getByTestId("reports-panel");
  await expect(panel).toContainText("No reports yet.");
  await panel.getByRole("button", { name: "Generate JSON" }).click();
  const json = page.getByTestId("report-json-v1");
  await expect(json).toContainText("Ready", { timeout: 60_000 });
  await panel.getByRole("button", { name: "Generate PDF" }).click();
  const pdf = page.getByTestId("report-pdf-v1");
  await expect(pdf).toContainText("Ready", { timeout: 60_000 });

  const download = page.waitForEvent("download");
  await pdf.getByRole("link", { name: "Download" }).click();
  expect((await download).suggestedFilename()).toMatch(/-report-v1\.pdf$/);
  const href = (await pdf.getByRole("link", { name: "Download" }).getAttribute("href")) ?? "";
  const response = await page.request.get(href);
  expect(response.status()).toBe(200);
  expect((await response.body()).subarray(0, 5).toString()).toBe("%PDF-");
  expect(response.headers()["x-content-sha256"]).toMatch(/^[0-9a-f]{64}$/);

  // The requester is told when each report is ready.
  await page.reload();
  await expect(page.getByTestId("unread-count")).toHaveText("2", { timeout: 30_000 });
  await page.getByTestId("notification-bell").click();
  const dialog = page.getByRole("dialog", { name: "Notifications" });
  await expect(dialog).toContainText("Report v1 (PDF) ready");
  await dialog.getByText("Report v1 (PDF) ready").click();
  await expect(page).toHaveURL(new RegExp(`/claims/${claimId}\\?tab=reports`));
  await expect(page.getByTestId("unread-count")).toHaveText("1");

  await page.getByRole("link", { name: "Reports", exact: true }).click();
  await expect(page.getByTestId("recent-reports")).toContainText("v1 · PDF");

  await page.getByRole("link", { name: "Integrations" }).click();
  await expect(page.getByTestId("messaging")).toContainText("Adapter only");
  await page.getByRole("button", { name: "Send me a test email" }).click();
  await expect(page.getByTestId("messaging")).toContainText("Test message sent (smtp)");

  const form = page.getByTestId("webhook-form");
  await form.getByLabel("Endpoint URL (https)").fill("http://example.com/claimos");
  await form.getByText("report.ready").click();
  await form.getByRole("button", { name: "Add webhook" }).click();
  await expect(form.getByRole("alert")).toContainText("https");
  await form.getByLabel("Endpoint URL (https)").fill("https://example.com/claimos");
  await form.getByRole("button", { name: "Add webhook" }).click();
  await expect(page.getByTestId("webhook-secret")).toHaveText(/^whsec_/);
  const hook = page.getByTestId("webhook");
  await expect(hook).toContainText("Active");
  await hook.getByRole("button", { name: "Disable" }).click();
  await expect(hook).toContainText("Disabled");
});
